export function getLucideIconByName(name?: string | null): LucideIcon | null {
  if (!name || typeof name !== 'string') return null
  if (!Object.prototype.hasOwnProperty.call(CURATED_LUCIDE_ICONS, name)) {
    return null
  }
  return CURATED_LUCIDE_ICONS[name] ?? null
}
